// 2. CHANGE WEBSITE LANGUAGE
// ======================================

// Find the language selector in HTML.

const languageSelect =
    document.querySelector("#languageSelect");


// This function changes all translated text.

function changeLanguage(language) {

    const selectedLanguage = translations[language];

    // Change the browser's language setting.

    document.documentElement.lang = language;


    // Find every element with data-i18n.

    document.querySelectorAll("[data-i18n]")
        .forEach(function(element) {

            const key = element.dataset.i18n;

            // Check whether a translation exists.

            if (selectedLanguage[key]) {

                element.innerHTML = selectedLanguage[key];

            }

        });


    // Remember the selected language.

    localStorage.setItem("pulseguard-language", language);

}


// Run when a visitor chooses another language.

languageSelect.addEventListener("change", function(event) {

    changeLanguage(event.target.value);

});


// Restore the visitor's previous language.

const savedLanguage =
    localStorage.getItem("pulseguard-language") || "en";

languageSelect.value = savedLanguage;

changeLanguage(savedLanguage);


